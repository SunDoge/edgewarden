import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDirectory = resolve(root, "migrations");
const outputFile = resolve(root, "src/generated/database-migrations.ts");
const migrationFiles = readdirSync(migrationsDirectory)
	.filter((file) => /^\d+.*\.sql$/.test(file))
	.sort();

const migrations = migrationFiles.map((name) => ({
	name,
	sql: readFileSync(resolve(migrationsDirectory, name), "utf8"),
}));
const sourceHash = createHash("sha256")
	.update(JSON.stringify(migrations))
	.digest("hex");
const generated = `/* eslint-disable */
/**
 * Generated from apps/api/migrations/*.sql by generate-runtime-migrations.mjs.
 * Do not edit this file directly.
 * Source SHA-256: ${sourceHash}
 */
export const databaseMigrations = ${JSON.stringify(migrations, null, "\t")} as const;
`;

if (process.argv.includes("--check")) {
	if (readFileSync(outputFile, "utf8") !== generated) {
		throw new Error(
			"Runtime migrations are stale. Run `pnpm --filter @edgewarden/api db:codegen`.",
		);
	}
} else {
	mkdirSync(dirname(outputFile), { recursive: true });
	writeFileSync(outputFile, generated);
	console.log(`✓ ${migrationFiles.length} runtime migrations generated`);
}
